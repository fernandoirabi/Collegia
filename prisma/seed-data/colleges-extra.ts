import type { SeedCollege } from "./colleges";

const IMG = {
  boston: "/images/campus_boston.jpg",
  florida: "/images/campus_florida.jpg",
  nyc: "/images/campus_nyc.jpg",
  california: "/images/campus_california.jpg",
  hero: "/images/hero_campus.jpg",
};

function regionImage(region: SeedCollege["region"]): string {
  if (region === "WEST_COAST" || region === "SOUTHWEST") return IMG.california;
  if (region === "NORTHEAST" || region === "EAST_COAST") return IMG.boston;
  if (region === "SOUTH") return IMG.florida;
  return IMG.hero;
}

type CollegeInput = {
  name: string;
  slug: string;
  shortName?: string;
  city: string;
  state: string;
  stateCode: string;
  region: SeedCollege["region"];
  type: "PUBLIC" | "PRIVATE";
  setting?: "URBAN" | "SUBURBAN" | "RURAL";
  sizeCategory?: "SMALL" | "MEDIUM" | "LARGE";
  undergradEnrollment: number;
  acceptanceRate: number;
  avgGpa: number;
  satRange: [number, number];
  actRange: [number, number];
  graduationRate: number;
  studentFacultyRatio: string;
  tuitionInternational: number;
  roomAndBoard: number;
  intlAid?: boolean;
  meritScholarships?: boolean;
  needBasedAid?: boolean;
  meetsFullNeed?: boolean;
  avgAid?: number;
  intlPercentage?: number;
  toeflMin?: number;
  ieltsMin?: number;
  greekLife?: boolean;
  tags: string[];
  strongPrograms: string[];
  earlyAction?: string;
  earlyDecision?: string;
  regularDecision?: string;
  rolling?: boolean;
};

function c(i: CollegeInput): SeedCollege {
  const size = i.sizeCategory ?? "LARGE";
  const publicSchool = i.type === "PUBLIC";
  const tuitionInState = publicSchool ? Math.round(i.tuitionInternational * 0.35) : undefined;
  return {
    name: i.name,
    slug: i.slug,
    shortName: i.shortName,
    city: i.city,
    state: i.state,
    stateCode: i.stateCode,
    region: i.region,
    type: i.type,
    setting: i.setting ?? "SUBURBAN",
    sizeCategory: size,
    undergradEnrollment: i.undergradEnrollment,
    acceptanceRate: i.acceptanceRate,
    avgGpa: i.avgGpa,
    satRange: i.satRange,
    actRange: i.actRange,
    graduationRate: i.graduationRate,
    studentFacultyRatio: i.studentFacultyRatio,
    tuitionInState,
    tuitionOutOfState: publicSchool ? i.tuitionInternational : undefined,
    tuitionInternational: i.tuitionInternational,
    roomAndBoard: i.roomAndBoard,
    estimatedTotalCost: i.tuitionInternational + i.roomAndBoard,
    intlAid: i.intlAid ?? publicSchool,
    meritScholarships: i.meritScholarships ?? true,
    needBasedAid: i.needBasedAid ?? false,
    meetsFullNeed: i.meetsFullNeed ?? false,
    avgAid: i.avgAid,
    intlPercentage: i.intlPercentage ?? 5,
    toeflMin: i.toeflMin ?? 79,
    ieltsMin: i.ieltsMin ?? 6.0,
    greekLife: i.greekLife ?? publicSchool,
    website: `https://www.${i.slug}.edu`,
    image: regionImage(i.region),
    tags: i.tags,
    strongPrograms: i.strongPrograms,
    earlyAction: i.earlyAction,
    regularDecision: i.regularDecision,
    rolling: i.rolling ?? (!i.earlyAction && !i.regularDecision),
  };
}

