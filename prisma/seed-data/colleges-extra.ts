function augmentPrograms(c: SeedCollege): SeedCollege {
  const progs = new Set(c.strongPrograms);
  if (progs.has("Business")) {
    progs.add("Finance");
    progs.add("Marketing");
  }
  if (progs.has("Engineering") || progs.has("Computer Science")) {
    progs.add("Mathematics");
    progs.add("Physics");
    progs.add("Chemistry");
  }
  if (progs.has("Computer Science")) {
    progs.add("Data Science");
  }
  if (progs.has("Pre-Medicine")) {
    progs.add("Biology");
  }
  if (progs.has("Biology") || progs.has("Pre-Medicine")) {
    progs.add("Health Sciences");
  }
  return { ...c, strongPrograms: [...progs] };
}

